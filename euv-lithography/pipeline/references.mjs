import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { SOURCES } from "../authoring/model.mjs";

const root = new URL("../authoring/", import.meta.url);
const files = ["model.mjs", "plan.mjs", ...readdirSync(new URL("parts/", root)).map((f) => "parts/" + f)];
const text = Object.fromEntries(files.map((f) => [f, readFileSync(new URL(f, root), "utf8")]));

const PAPERS = { "Heertjes 2020": "heertjes2020", "Lowisch 2012": "lowisch2012", "Fomenkov 2017": "fomenkov" };
const patent = /\b(?:US|WO|EP)\d{6,12}(?:[A-Z]\d?)?\b/g;
const paper = /\b(?!Workshop|SPIE)[A-Z][a-z]+(?: et al\.)? (?:19|20)\d{2}\b/g;

function index(pattern, norm = (s) => s) {
  const hits = new Map();
  for (const [file, src] of Object.entries(text))
    for (const m of src.matchAll(pattern)) {
      const key = norm(m[0]);
      if (!hits.has(key)) hits.set(key, new Set());
      hits.get(key).add(file);
    }
  return [...hits].sort(([a], [b]) => a.localeCompare(b));
}

const cited = (set) => [...set].sort().map((f) => `\`${f}\``).join(", ");
const web = index(/\[([A-Za-z][A-Za-z0-9.-]+)\]/g, (s) => s.slice(1, -1)).filter(([k]) => SOURCES[k]);
const patents = index(patent);
const papers = index(paper, (s) => s.replace(" et al.", ""));

const md = `# References

Generated by \`npm run build:references\` from the source tags and citations in \`authoring/\`. A row lists every module that cites the source.
Rows without a link are citations whose full reference is not recorded in this repository.

## Web and publications

| Tag | Source | Cited in |
| --- | --- | --- |
${Object.keys(SOURCES)
  .sort()
  .map((k) => `| \`${k}\` | ${SOURCES[k]} | ${cited(new Map(web).get(k) ?? new Set(["model.mjs"]))} |`)
  .join("\n")}

## Patents

| Patent | Cited in |
| --- | --- |
${patents.map(([k, f]) => `| [${k}](https://patents.google.com/patent/${k}) | ${cited(f)} |`).join("\n")}

## Papers

| Citation | Link | Cited in |
| --- | --- | --- |
${papers.map(([k, f]) => `| ${k} | ${PAPERS[k] ? SOURCES[PAPERS[k]] : "not recorded"} | ${cited(f)} |`).join("\n")}
`;

writeFileSync(new URL("REFERENCES.md", root), md);
console.log(`authoring/REFERENCES.md: ${Object.keys(SOURCES).length} web, ${patents.length} patents, ${papers.length} papers`);
